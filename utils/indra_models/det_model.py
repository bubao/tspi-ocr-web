        v_73 = F.interpolate(v_70, mode='nearest', size=(256,256))
        v_74 = (v_72 + v_73)
        v_75 = self.conv2d_34(v_74)
        v_76 = F.hardswish(v_75)
        v_77 = self.conv2d_35(v_2)
        v_78 = F.hardswish(v_77)
        v_79 = v_78.reshape(1, 4, 256, 2, 256, 2)
        v_80 = v_79.permute(dims=(0,1,3,5,2,4))
        v_81 = v_80.reshape(1, 16, 256, 256)
        v_82 = torch.cat((v_76, v_81), dim=1)
        v_83 = self.conv2d_36(v_82)
        v_84 = F.hardswish(v_83)
        v_85 = self.conv2d_37(v_84)
        v_86 = F.hardswish(v_85)
        v_87 = self.conv2d_38(v_86)
        v_88 = F.pixel_shuffle(v_87, upscale_factor=2)
        v_89, v_90 = torch.tensor_split(v_88, dim=1, indices=(1,))
        v_91 = F.softplus(v_90, beta=1.0, threshold=20.0)
        v_92 = (v_91 * 8.0)
        v_93 = torch.cat((v_89, v_92), dim=1)
        return v_93

